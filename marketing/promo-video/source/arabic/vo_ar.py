import json, sherpa_onnx, soundfile as sf, numpy as np, sys
d="vits-piper-ar_JO-kareem-medium/"
tts=sherpa_onnx.OfflineTts(sherpa_onnx.OfflineTtsConfig(model=sherpa_onnx.OfflineTtsModelConfig(
    vits=sherpa_onnx.OfflineTtsVitsModelConfig(model=d+"ar_JO-kareem-medium.onnx",tokens=d+"tokens.txt",data_dir=d+"espeak-ng-data"),num_threads=4)))
lines=[
 ("hook","عَمَلُكَ يَسْتَحِقُّ تَسْوِيقًا رَائِعًا. لَكِنْ، فِي كُلِّ شَهْرٍ، تَتَكَرَّرُ الْقِصَّةُ نَفْسُهَا."),
 ("problem","سَاعَاتٌ مِنَ التَّفْكِيرِ. تَعْدِيلَاتٌ لَا تَنْتَهِي مَعَ الْمُصَمِّمِينَ. وَكَالَاتٌ مُكْلِفَةٌ. وَمَنْشُورَاتٌ تَتَأَخَّرُ عَنْ مَوْعِدِهَا."),
 ("meet","تَعَرَّفْ عَلَى وَكِيل. مُدِيرُ التَّسْوِيقِ الذَّكِيُّ لِشَرِكَتِكَ."),
 ("brand","يَبْدَأُ وَكِيل بِفَهْمِ عَلَامَتِكَ التِّجَارِيَّةِ: نَشَاطِكَ، وَجُمْهُورِكَ، وَأُسْلُوبِكَ، وَأَلْوَانِكَ، وَخُطُوطِكَ، وَشِعَارِكَ."),
 ("plan","اِخْتَرِ الشَّهْرَ وَالْمِنَصَّاتِ، وَخِلَالَ دَقَائِقَ، يَبْنِي لَكَ وَكِيل اسْتِرَاتِيجِيَّةً مُتَكَامِلَةً: الْأَهْدَافَ، وَمَحَاوِرَ الْمُحْتَوَى، وَالْمُنَاسَبَاتِ الْمُهِمَّةَ، وَكُلَّ مَنْشُورٍ بِنَصِّهِ، وَوُسُومِهِ، وَأَفْضَلِ وَقْتٍ لِنَشْرِهِ."),
 ("design","ثُمَّ يُصَمِّمُ كُلَّ مَنْشُورٍ بِهُوِيَّتِكَ، جَاهِزًا لِإِنْسْتَغْرَام، وَفِيسْبُوك، وَتِيك تُوك."),
 ("review","كُلُّ شَيْءٍ فِي تَقْوِيمٍ ذَكِيٍّ وَاحِدٍ. اِسْحَبْ لِتَغْيِيرِ الْمَوْعِدِ، وَأَعِدِ الصِّيَاغَةَ بِنَقْرَةٍ، وَأَرْسِلِ الْمَنْشُورَاتِ لِلِاعْتِمَادِ. بَلْ شَارِكْ رَابِطًا آمِنًا، لِيَعْتَمِدَ عُمَلَاؤُكَ دُونَ حِسَابٍ."),
 ("publish","وَبَعْدَ الِاعْتِمَادِ، اِنْشُرْ بِنَقْرَةٍ وَاحِدَةٍ، أَوْ دَعْ وَكِيل يَنْشُرُ تِلْقَائِيًّا فِي الْوَقْتِ الْمُحَدَّدِ."),
 ("team","حِسَابٌ وَاحِدٌ. شَرِكَاتٌ مُتَعَدِّدَةٌ. وَفَرِيقُكَ كُلُّهُ يَعْمَلُ مَعًا."),
 ("cta","وَكِيل. تَسْوِيقُكَ يَعْمَلُ وَحْدَهُ. اِبْدَأِ الْيَوْمَ عَبْرَ مَوْقِعِنَا الظَّاهِرِ عَلَى الشَّاشَةِ."),
 ("credit","وَكِيل، خِدْمَةٌ مُقَدَّمَةٌ مِنْ إِنْجَاز لِتِقْنِيَةِ الْمَعْلُومَاتِ."),
]
speed=float(sys.argv[1]) if len(sys.argv)>1 else 0.95
meta=[]
for n,t in lines:
    a=tts.generate(t,sid=0,speed=speed); s=np.array(a.samples)
    # trim silence edges
    idx=np.where(np.abs(s)>0.01)[0]; s=s[max(0,idx[0]-400):idx[-1]+2000]
    sf.write(f"vo/{n}.wav",s,a.sample_rate); meta.append({"name":n,"dur":round(len(s)/a.sample_rate,3),"text":t}); print(n,meta[-1]["dur"])
json.dump(meta,open("vo/meta.json","w"),ensure_ascii=False,indent=1); print("total",sum(m["dur"] for m in meta))
